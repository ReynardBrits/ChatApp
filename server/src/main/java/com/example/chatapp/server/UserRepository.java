package com.example.chatapp.server;

import org.sqlite.SQLiteErrorCode;
import org.sqlite.SQLiteException;

import java.security.GeneralSecurityException;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

public final class UserRepository {

    private final ServerDatabase database;

    // Safe user details to return to clients.
    public record Account(int id, String username) {
    }

    public UserRepository(ServerDatabase database) {
        this.database = database;
    }

    public Account register(String username, String password)
            throws SQLException, GeneralSecurityException {

        String normalized = normalizeUsername(username);

        if (!normalized.matches("[a-z0-9_]{3,24}")) {
            throw new IllegalArgumentException(
                    "Username must contain 3 to 24 letters, numbers or underscores."
            );
        }

        if (password == null
                || password.length() < 8
                || password.length() > 128) {
            throw new IllegalArgumentException(
                    "Password must contain 8 to 128 characters."
            );
        }

        String passwordHash = PasswordHasher.hashPassword(password);

        String sql = """
                INSERT INTO users (username, password_hash)
                VALUES (?, ?)
                """;

        try (Connection connection = database.openConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, normalized);
            statement.setString(2, passwordHash);
            statement.executeUpdate();

            // Read the ID generated by this connection's insert.
            try (Statement query = connection.createStatement();
                 ResultSet result = query.executeQuery(
                         "SELECT last_insert_rowid()"
                 )) {

                result.next();
                return new Account(result.getInt(1), normalized);
            }

        } catch (SQLiteException exception) {
            if (exception.getResultCode()
                    == SQLiteErrorCode.SQLITE_CONSTRAINT_UNIQUE) {
                throw new IllegalArgumentException(
                        "That username is already taken."
                );
            }

            throw exception;
        }
    }

    public Account authenticate(String username, String password)
            throws SQLException, GeneralSecurityException {

        String normalized = normalizeUsername(username);

        if (!normalized.matches("[a-z0-9_]{3,24}")
                || password == null
                || password.length() < 8
                || password.length() > 128) {
            return null;
        }

        String sql = """
                SELECT id, username, password_hash
                FROM users
                WHERE username = ?
                LIMIT 1
                """;

        Account account;
        String passwordHash;

        try (Connection connection = database.openConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, normalized);

            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) {
                    return null;
                }

                account = new Account(
                        result.getInt("id"),
                        result.getString("username")
                );

                passwordHash = result.getString("password_hash");
            }
        }

        return PasswordHasher.verifyPassword(password, passwordHash)
                ? account
                : null;
    }

    public Account findByUsername(String username) throws SQLException {
        String sql = """
                SELECT id, username
                FROM users
                WHERE username = ?
                LIMIT 1
                """;

        try (Connection connection = database.openConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, normalizeUsername(username));

            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) {
                    return null;
                }

                return new Account(
                        result.getInt("id"),
                        result.getString("username")
                );
            }
        }
    }

    public List<Account> getOtherUsers(int currentUserId)
            throws SQLException {

        List<Account> users = new ArrayList<>();

        String sql = """
                SELECT id, username
                FROM users
                WHERE id <> ?
                ORDER BY username ASC
                """;

        try (Connection connection = database.openConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setInt(1, currentUserId);

            try (ResultSet result = statement.executeQuery()) {
                while (result.next()) {
                    users.add(new Account(
                            result.getInt("id"),
                            result.getString("username")
                    ));
                }
            }
        }

        return users;
    }

    private static String normalizeUsername(String username) {
        return username == null
                ? ""
                : username.trim().toLowerCase(Locale.ROOT);
    }
}